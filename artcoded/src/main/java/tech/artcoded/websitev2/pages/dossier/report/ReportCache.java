package tech.artcoded.websitev2.pages.dossier.report;

import java.io.IOException;
import java.io.Serializable;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.Duration;
import java.time.Instant;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;
import java.util.concurrent.locks.ReentrantLock;
import java.util.function.Supplier;
import java.util.stream.Stream;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.cache.Cache;
import org.springframework.cache.CacheManager;
import org.springframework.cache.concurrent.ConcurrentMapCache;
import org.springframework.stereotype.Component;

import lombok.extern.slf4j.Slf4j;
import tech.artcoded.websitev2.pages.dossier.report.DossierReportService.ReportFile;

/**
 * The generated reports (pdf), kept so that a report is computed and rendered once: the pdf in a folder
 * (application.reports.cache-dir), its entry in the spring cache {@value #CACHE} (redis): the path of the pdf and the
 * report model (the insights of the mail), not the bytes.
 * <p>
 * An entry lives application.reports.cache-ttl (7 days by default). Every entry is invalidated, and its pdf deleted,
 * when what a report is computed from changes (a dossier, an invoice, an expense, the organization, the report
 * template: {@link ReportCacheInvalidator}), since every report compares with the other periods and counts what is not
 * processed yet. A pdf older than the ttl is deleted too (its entry expired).
 * <p>
 * A report is generated once even when asked twice at the same time (a lock per key), and a report generated while the
 * cache was invalidated is returned but not kept (it may be computed from the data before the change).
 */
@Component
@Slf4j
public class ReportCache {
    public static final String CACHE = "dossier_reports";

    /** what the cache keeps: the pdf is a file, the model is small */
    public record CachedReport(String key, String path, String fileName, DossierReport report) implements Serializable {
    }

    private final Cache cache;
    private final Path directory;
    private final Duration ttl;
    /** incremented by each invalidation: a report generated across one isn't kept */
    private final AtomicLong generation = new AtomicLong();
    private final ConcurrentHashMap<String, ReentrantLock> locks = new ConcurrentHashMap<>();

    public ReportCache(CacheManager cacheManager,
            @Value("${application.reports.cache-dir:${java.io.tmpdir}/cache-reports}") String directory,
            @Value("${application.reports.cache-ttl:7d}") Duration ttl) {
        this.cache = Optional.ofNullable(cacheManager.getCache(CACHE)).orElseGet(() -> {
            log.warn("no cache {} in the cache manager: reports cached in memory", CACHE);
            return new ConcurrentMapCache(CACHE);
        });
        this.directory = Path.of(directory);
        this.ttl = ttl;
        try {
            Files.createDirectories(this.directory);
        } catch (IOException e) {
            throw new IllegalStateException("cannot create the report cache directory " + directory, e);
        }
        sweep();
    }

    /** The report of the key: the cached one, or the one generated (then kept). */
    public ReportFile get(String key, Supplier<ReportFile> generator) {
        var cached = read(key);
        if (cached.isPresent()) {
            return cached.get();
        }
        var lock = locks.computeIfAbsent(key, k -> new ReentrantLock());
        lock.lock();
        try {
            // generated by another request while this one waited
            cached = read(key);
            if (cached.isPresent()) {
                return cached.get();
            }
            var started = generation.get();
            var file = generator.get();
            if (generation.get() == started) {
                store(key, file);
            } else {
                log.info("report {} generated during an invalidation: not cached", key);
            }
            return file;
        } finally {
            lock.unlock();
        }
    }

    /** the cached report of the key, empty when not cached, or when its pdf is gone (the entry is dropped) */
    Optional<ReportFile> read(String key) {
        CachedReport cached;
        try {
            cached = cache.get(key, CachedReport.class);
        } catch (RuntimeException e) {
            // e.g. an entry of a previous version of the model
            log.warn("cached report {} not readable, dropped: {}", key, e.getMessage());
            cache.evict(key);
            return Optional.empty();
        }
        if (cached == null) {
            return Optional.empty();
        }
        var path = Path.of(cached.path());
        try {
            var bytes = Files.readAllBytes(path);
            log.debug("report {} from the cache ({})", key, path);
            return Optional.of(new ReportFile(cached.fileName(), bytes, cached.report()));
        } catch (IOException e) {
            log.info("the pdf of the cached report {} is gone ({}): generated again", key, path);
            cache.evict(key);
            return Optional.empty();
        }
    }

    private void store(String key, ReportFile file) {
        var path = directory.resolve("%s-%s.pdf".formatted(key.replaceAll("[^A-Za-z0-9._-]+", "_"), UUID.randomUUID()));
        try {
            var tmp = directory.resolve(path.getFileName() + ".tmp");
            Files.write(tmp, file.content());
            Files.move(tmp, path, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
            cache.put(key, new CachedReport(key, path.toString(), file.fileName(), file.report()));
            log.info("report {} cached ({})", key, path);
        } catch (Exception e) {
            // the report is returned anyway: the next request generates it again
            log.warn("report {} not cached: {}", key, e.getMessage());
            delete(path);
        }
        sweep();
    }

    /** drops the report of a key and deletes its pdf (to generate it again) */
    public void evict(String key) {
        var lock = locks.computeIfAbsent(key, k -> new ReentrantLock());
        lock.lock();
        try {
            try {
                Optional.ofNullable(cache.get(key, CachedReport.class)).map(c -> Path.of(c.path()))
                        .ifPresent(this::delete);
            } catch (RuntimeException e) {
                log.debug("entry of {} not readable: {}", key, e.getMessage());
            }
            cache.evict(key);
        } finally {
            lock.unlock();
        }
    }

    /** drops every report and deletes their pdf: what they are computed from changed */
    public void invalidateAll(String reason) {
        generation.incrementAndGet();
        cache.clear();
        var deleted = deleteFiles(path -> true);
        if (deleted > 0) {
            log.info("report cache invalidated ({}): {} report(s) deleted", reason, deleted);
        }
    }

    /** deletes the pdf older than the ttl: their entry expired */
    void sweep() {
        var limit = Instant.now().minus(ttl);
        var deleted = deleteFiles(path -> {
            try {
                return Files.getLastModifiedTime(path).toInstant().isBefore(limit);
            } catch (IOException e) {
                return false;
            }
        });
        if (deleted > 0) {
            log.info("{} expired report(s) deleted", deleted);
        }
    }

    private long deleteFiles(java.util.function.Predicate<Path> which) {
        try (Stream<Path> files = Files.list(directory)) {
            return files.filter(Files::isRegularFile).filter(
                    p -> p.getFileName().toString().endsWith(".pdf") || p.getFileName().toString().endsWith(".tmp"))
                    .filter(which).filter(this::delete).count();
        } catch (IOException e) {
            log.warn("cannot list the report cache directory {}: {}", directory, e.getMessage());
            return 0;
        }
    }

    private boolean delete(Path path) {
        try {
            return Files.deleteIfExists(path);
        } catch (IOException e) {
            log.warn("cannot delete the cached report {}: {}", path, e.getMessage());
            return false;
        }
    }

    Path directory() {
        return directory;
    }
}
